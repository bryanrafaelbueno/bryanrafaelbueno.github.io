const root = document.documentElement;
const header = document.querySelector("[data-header]");
const menuButton = document.querySelector("[data-menu-toggle]");
const mobileMenu = document.querySelector("[data-mobile-menu]");
const languageButtons = document.querySelectorAll("[data-language]");
const languageContent = document.querySelectorAll("[data-language-content]");
const progressBar = document.querySelector(".scroll-progress span");
const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");

function setLanguage(language) {
  const chosen = translations[language] ? language : "pt";
  root.lang = chosen === "pt" ? "pt-BR" : "en";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[chosen][key]) element.textContent = translations[chosen][key];
  });

  languageContent.forEach((element) => {
    element.hidden = element.dataset.languageContent !== chosen;
  });

  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === chosen));
  });

  const description =
    chosen === "pt"
      ? "Portfólio de Bryan Rafael Bueno Ribeiro, desenvolvedor de software com projetos web, mobile, desktop e de sistemas."
      : "Portfolio of Bryan Rafael Bueno Ribeiro, a software developer building useful web, mobile, desktop, and systems products.";
  document.querySelector('meta[name="description"]').setAttribute("content", description);
  document.title =
    chosen === "pt"
      ? "Bryan Rafael Bueno Ribeiro | Desenvolvedor de Software"
      : "Bryan Rafael Bueno Ribeiro | Software Developer";

  try {
    localStorage.setItem("portfolio-language", chosen);
  } catch {
    // The language still works when storage is unavailable.
  }
}

function closeMenu() {
  document.body.classList.remove("menu-open");
  header.classList.remove("menu-active");
  menuButton.setAttribute("aria-expanded", "false");
}

menuButton.addEventListener("click", () => {
  const willOpen = menuButton.getAttribute("aria-expanded") !== "true";
  menuButton.setAttribute("aria-expanded", String(willOpen));
  document.body.classList.toggle("menu-open", willOpen);
  header.classList.toggle("menu-active", willOpen);
});

mobileMenu.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeMenu));

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

function updateScrollState() {
  const scrollTop = window.scrollY;
  const scrollable = document.documentElement.scrollHeight - window.innerHeight;
  header.classList.toggle("scrolled", scrollTop > 18);
  progressBar.style.width = `${scrollable > 0 ? (scrollTop / scrollable) * 100 : 0}%`;
}

window.addEventListener("scroll", updateScrollState, { passive: true });
window.addEventListener("resize", () => {
  updateScrollState();
  if (window.innerWidth > 820) closeMenu();
});

const revealElements = document.querySelectorAll(".reveal");
if (reducedMotion.matches || !("IntersectionObserver" in window)) {
  revealElements.forEach((element) => element.classList.add("is-visible"));
} else {
  const revealObserver = new IntersectionObserver(
    (entries, observer) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -7%" },
  );
  revealElements.forEach((element) => revealObserver.observe(element));
}

const sections = document.querySelectorAll("main section[id]");
const navLinks = document.querySelectorAll('.desktop-nav a[href^="#"]');
if ("IntersectionObserver" in window) {
  const navObserver = new IntersectionObserver(
    (entries) => {
      const visible = entries
        .filter((entry) => entry.isIntersecting)
        .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];
      if (!visible) return;
      navLinks.forEach((link) => {
        link.classList.toggle("active", link.getAttribute("href") === `#${visible.target.id}`);
      });
    },
    { rootMargin: "-28% 0px -58%", threshold: [0, 0.2, 0.5] },
  );
  sections.forEach((section) => navObserver.observe(section));
}

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeMenu();
});

document.querySelector("[data-year]").textContent = new Date().getFullYear();

let initialLanguage = "pt";
try {
  const queryLanguage = new URLSearchParams(window.location.search).get("lang");
  initialLanguage = queryLanguage || localStorage.getItem("portfolio-language") || "pt";
} catch {
  initialLanguage = "pt";
}
setLanguage(initialLanguage);
updateScrollState();
